import {
  Body,
  Controller,
  Get,
  HttpStatus,
  Param,
  ParseUUIDPipe,
  Post,
  Res,
} from '@nestjs/common';
import {
  ApiBadGatewayResponse,
  ApiBadRequestResponse,
  ApiConflictResponse,
  ApiCreatedResponse,
  ApiHeader,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiTags,
  ApiUnprocessableEntityResponse,
} from '@nestjs/swagger';
import type { Response } from 'express';
import { CreateTransaction } from '../../application/transactions/create-transaction.use-case';
import { GetTransaction } from '../../application/transactions/get-transaction.use-case';
import { GetTransactionByKey } from '../../application/transactions/get-transaction-by-key.use-case';
import { IdempotencyKey } from './idempotency-key.decorator';
import { unwrapOrThrow } from './result-to-http';
import {
  CreateTransactionDto,
  toTransactionResponse,
  TransactionResponseDto,
} from './transaction.dto';

/** HTTP adapter only: delegates to use cases and maps the Result to HTTP. */
@ApiTags('transactions')
@Controller('transactions')
export class TransactionsController {
  constructor(
    private readonly createTransaction: CreateTransaction,
    private readonly getTransaction: GetTransaction,
    private readonly getTransactionByKey: GetTransactionByKey,
  ) {}

  @Post()
  @ApiOperation({
    summary:
      'Pay: stores PENDING, charges the card at the gateway and applies the final status',
  })
  @ApiHeader({
    name: 'Idempotency-Key',
    required: false,
    description:
      'UUID generated by the client; replays return the same transaction',
  })
  @ApiCreatedResponse({
    type: TransactionResponseDto,
    description: 'Created (status may still be PENDING)',
  })
  @ApiOkResponse({
    type: TransactionResponseDto,
    description: 'Same Idempotency-Key: existing transaction',
  })
  @ApiBadRequestResponse({ description: 'Malformed body or header' })
  @ApiNotFoundResponse({ description: 'Product or customer not found' })
  @ApiConflictResponse({
    description:
      'Not enough stock, or Idempotency-Key reused with another body',
  })
  @ApiUnprocessableEntityResponse({
    description: 'Card fails Luhn, is expired or its brand is not supported',
  })
  @ApiBadGatewayResponse({ description: 'The payment gateway failed' })
  async create(
    @Body() body: CreateTransactionDto,
    @IdempotencyKey(new ParseUUIDPipe({ optional: true }))
    idempotencyKey: string | undefined,
    @Res({ passthrough: true }) res: Response,
  ): Promise<TransactionResponseDto> {
    const { transaction, created } = unwrapOrThrow(
      await this.createTransaction.execute({
        ...body,
        idempotencyKey: idempotencyKey ?? null,
      }),
    );
    res.status(created ? HttpStatus.CREATED : HttpStatus.OK);
    return toTransactionResponse(transaction);
  }

  // Declared before ':id' so that "by-key" is not parsed as an id.
  @Get('by-key/:idempotencyKey')
  @ApiOperation({
    summary:
      'Recover a payment by the Idempotency-Key the client sent (refreshed if PENDING)',
  })
  @ApiOkResponse({ type: TransactionResponseDto })
  @ApiBadRequestResponse({ description: 'key is not a UUID' })
  @ApiNotFoundResponse({ description: 'No transaction for that key' })
  @ApiBadGatewayResponse({ description: 'The payment gateway failed' })
  async findByKey(
    @Param('idempotencyKey', new ParseUUIDPipe()) key: string,
  ): Promise<TransactionResponseDto> {
    return toTransactionResponse(
      unwrapOrThrow(await this.getTransactionByKey.execute(key)),
    );
  }

  @Get(':id')
  @ApiOperation({
    summary: 'Get a transaction; if PENDING it is refreshed from the gateway',
  })
  @ApiOkResponse({ type: TransactionResponseDto })
  @ApiBadRequestResponse({ description: 'id is not a UUID' })
  @ApiNotFoundResponse({ description: 'Transaction not found' })
  @ApiBadGatewayResponse({ description: 'The payment gateway failed' })
  async findOne(
    @Param('id', new ParseUUIDPipe()) id: string,
  ): Promise<TransactionResponseDto> {
    return toTransactionResponse(
      unwrapOrThrow(await this.getTransaction.execute(id)),
    );
  }
}
